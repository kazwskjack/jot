test('paused task and cancelled run revoke bound tool access independently of agent status', async t => {
  const { service, db } = fixture(t);
  const a = service.createAgent('a', { name: 'A' });
  const tasks = new PersistentTaskService(db, service);
  const task = tasks.create('a', { title: 'Task', agent_id: a.agent_id, objective: 'Read', trigger: { kind: 'once' }, budget: { max_runs: 3 } });
  await tasks.tick();
  const runId = tasks.occurrences('a', task.task_id).items[0].run_id;
  tasks.pause('a', task.task_id, tasks.get('a', task.task_id).version);
  assert.equal(service.getAgent('a', a.agent_id).status, 'active');
  assert.throws(() => service.listMemory('a', 'ws-1', {}, runId), /task_generation_revoked/);
  const chat = service.enqueueAgentMessage('a', a.agent_id, { text: 'chat', client_message_id: 'chat' });
  db.prepare("UPDATE ga_runs SET status='cancelled' WHERE id=?").run(chat.run_id);
  assert.throws(() => service.listMessages('a', 'ws-1', chat.run_id), /run_capability_revoked/);
});
