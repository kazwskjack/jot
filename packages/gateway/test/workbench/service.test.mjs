test('deletion revokes bound capabilities, cancels queued runs and is restart recoverable', t => {
  const { service, db, root } = fixture(t);
  const a = service.createAgent('a', { name: 'A' });
  const b = service.createAgent('a', { name: 'B' });
  const run = service.enqueueAgentMessage('a', a.agent_id, { text: 'Task', client_message_id: 'task' });
  service.saveMemory('a', 'ws-1', { scope: 'project', project_id: a.project_id, content: 'Keep shared' });
  service.sendMessage('a', 'ws-1', { sender_agent_id: b.agent_id, recipient_agent_id: a.agent_id, text: 'Message', client_message_id: 'delete-msg' });
  assert.equal(service.deletionPreview('a', a.agent_id).active_runs.length, 1);
  service.beginDeletion('a', a.agent_id, 1);
  assert.throws(() => service.contextForRun(run.run_id), /agent_capability_revoked/);
  const restarted = new WorkbenchService(db, { workspaceIds: ['ws-1'], root: join(root, 'shared') });
  restarted.resumeDeletions();
  assert.equal(restarted.getAgent('a', a.agent_id).status, 'deleted');
  assert.equal(db.prepare('SELECT status FROM ga_runs WHERE id=?').get(run.run_id).status, 'cancelled');
  assert.equal(restarted.getAgent('a', b.agent_id).status, 'active');
  assert.equal(restarted.listMemory('a', 'ws-1', {}).items.length, 1);
  assert.equal(restarted.listMessages('a', 'ws-1').items[0].status, 'recipient_deleted');
  assert.equal(restarted.deleteAgent('a', a.agent_id, restarted.getAgent('a', a.agent_id).version).status, 'deleted');
});
test('mailbox uses a real queued run and publishes only completed assistant output with bounded replies', t => {
  const { service, db } = fixture(t);
  const a = service.createAgent('a', { name: 'A' });
  const b = service.createAgent('a', { name: 'B' });
  const input = { sender_agent_id: a.agent_id, recipient_agent_id: b.agent_id, text: 'Review', client_message_id: 'm1', auto_reply: true, max_replies: 1 };
  const msg = service.sendMessage('a', 'ws-1', input);
  assert.equal(service.sendMessage('a', 'ws-1', input).message_id, msg.message_id);
  assert.throws(() => service.sendMessage('a', 'ws-1', { ...input, client_message_id: 'fake', initiator: 'agent' }), /invalid_message_identity/);
  service.processMailbox();
  const processing = service.listMessages('a', 'ws-1').items[0];
  assert.equal(processing.status, 'processing');
  assert.equal(service.contextForRun(processing.run_id).kind, 'internal_mailbox');
  assert.notEqual(db.prepare('SELECT conversation_id FROM ga_runs WHERE id=?').get(processing.run_id).conversation_id, b.conversation_id);
  assert.notEqual(db.prepare('SELECT c.archived_at FROM ga_conversations c JOIN ga_runs r ON r.conversation_id=c.id WHERE r.id=?').get(processing.run_id).archived_at, null);
  service.processMailbox();
  assert.equal(db.prepare('SELECT count(*) n FROM ga_runs').get().n, 1);
  const runs = new RunRepository(db, new EventStore(db));
  db.exec('BEGIN');
  runs.appendAssistant(processing.run_id, 'Reviewed with evidence');
  runs.finalizePublication(processing.run_id, 'succeeded', null);
  db.exec('COMMIT');
  service.processMailbox();
  const messages = service.listMessages('a', 'ws-1').items;
  assert.equal(messages[0].status, 'completed');
  assert.equal(messages[1].text, 'Reviewed with evidence');
  assert.equal(messages[1].initiator, 'agent');
  assert.equal(messages[1].reply_to, msg.message_id);
  service.processMailbox();
  assert.equal(db.prepare('SELECT count(*) n FROM ga_runs').get().n, 1);
});
