// Translate owned task UI notices only; raw task content and unknown errors stay original.
export function taskUiMessage(value:string,language:ApplicationLanguage){
 return language==='en'&&Object.hasOwn(english,value)?english[value]!:value;
}

// Only for output produced by readinessReason; retain its opaque reference suffix.
export function taskReadinessMessage(value:string,language:ApplicationLanguage){
 if(language!=='en')return value;
 for(const prefix of ['等待前置任务完成','前置任务缺少证据','需要补充证据','缺少前置条件','前置条件待核验','能力待核验','能力暂不可用','能力状态异常','能力状态待确认']){
  if(value.startsWith(prefix+'：'))return english[prefix]+': '+value.slice(prefix.length+1);
 }
 return taskUiMessage(value,language);
}
